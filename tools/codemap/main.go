// Command codemap writes docs/CODEMAP.md: a map of the code for people and
// coding agents, so a new session can find its way without reading the tree.
//
//	go run ./tools/codemap          # regenerate docs/CODEMAP.md
//	go run ./tools/codemap -check   # CI: fail if it is out of date
//
// For every Go package it lists the package's purpose (the first sentence of
// its doc comment), which internal packages it imports and is imported by,
// and, per file, its purpose (its leading comment) and its top-level
// declarations. There are no line numbers or counts, so the map changes only
// when declarations are added, removed or renamed, not on every edit. Tests are listed by
// name. The web client and the dashboard page are listed by function.
//
// It uses only the standard library (go/parser), so it needs nothing
// installed, and its output is deterministic (no dates, sorted), so the
// check is stable.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	module = "github.com/dmdhrumilmistry/setu"
	out    = "docs/CODEMAP.md"
)

type file struct {
	name    string
	purpose string
	decls   []string // "Name:line"
	tests   []string
}

type pkg struct {
	dir     string // relative, slash separated
	name    string
	doc     string
	imports map[string]bool // internal import paths (relative dirs)
	files   []*file
	tests   []*file
}

func main() {
	check := flag.Bool("check", false, "fail if "+out+" is out of date instead of writing it")
	flag.Parse()
	root, err := findRoot()
	if err != nil {
		fatal(err)
	}
	b, err := generate(root)
	if err != nil {
		fatal(err)
	}
	path := filepath.Join(root, out)
	if *check {
		old, _ := os.ReadFile(path)
		if !bytes.Equal(old, b) {
			fatal(fmt.Errorf("%s is out of date: run `go run ./tools/codemap`", out))
		}
		fmt.Println("code map is up to date")
		return
	}
	if err := os.WriteFile(path, b, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d bytes)\n", out, len(b))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "codemap:", err)
	os.Exit(1)
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if b, err := os.ReadFile(filepath.Join(dir, "go.mod")); err == nil && bytes.Contains(b, []byte("module "+module+"\n")) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("run inside the %s module", module)
		}
		dir = parent
	}
}

func generate(root string) ([]byte, error) {
	pkgs, err := goPackages(root)
	if err != nil {
		return nil, err
	}
	var w bytes.Buffer
	p := func(format string, a ...any) { fmt.Fprintf(&w, format, a...) }
	p("# Code map\n\n")
	p("Generated by `go run ./tools/codemap` from the source; do not edit by hand. CI fails when it is out of date.\n\n")
	p("Start here to find where something lives, then open only the files you need (grep for a name to get its line). Methods are `Type.Method`; functions and methods are listed whether exported or not, types, constants and variables when exported. It holds no line numbers, so it changes only when declarations are added, removed or renamed. AGENTS.md has the architecture and conventions; docs/DESIGN.md the wire protocol.\n\n")

	p("## Packages\n\n| Package | Purpose | Imports (internal) |\n| --- | --- | --- |\n")
	for _, k := range pkgs {
		p("| [`%s`](#%s) | %s | %s |\n", k.dir, anchor(k.dir), cell(k.doc), cell(strings.Join(sortedKeys(k.imports), ", ")))
	}
	p("\n")

	importedBy := map[string][]string{}
	for _, k := range pkgs {
		for imp := range k.imports {
			importedBy[imp] = append(importedBy[imp], k.dir)
		}
	}
	for _, k := range pkgs {
		p("## %s\n\n", k.dir)
		if k.doc != "" {
			p("%s\n\n", k.doc)
		}
		if by := importedBy[k.dir]; len(by) > 0 {
			sort.Strings(by)
			p("Imported by: %s.\n\n", strings.Join(by, ", "))
		}
		for _, f := range k.files {
			p("- **%s**", f.name)
			if f.purpose != "" {
				p(" — %s", f.purpose)
			}
			if len(f.decls) > 0 {
				p("<br>%s", strings.Join(f.decls, ", "))
			}
			p("\n")
		}
		if len(k.tests) > 0 {
			p("\nTests:\n")
			for _, f := range k.tests {
				p("- %s: %s\n", f.name, strings.Join(f.tests, ", "))
			}
		}
		p("\n")
	}

	p("## JavaScript\n\nThe web client (`web/js`, served from GitHub Pages) and the dashboard page (embedded in the binary).\n\n")
	for _, glob := range []string{"web/js/*.mjs", "internal/dashboard/static/*.js", "web/test/*.mjs"} {
		matches, _ := filepath.Glob(filepath.Join(root, filepath.FromSlash(glob)))
		sort.Strings(matches)
		for _, m := range matches {
			f, err := jsFile(m)
			if err != nil {
				return nil, err
			}
			rel, _ := filepath.Rel(root, m)
			p("- **%s**", filepath.ToSlash(rel))
			if f.purpose != "" {
				p(" — %s", f.purpose)
			}
			if len(f.decls) > 0 {
				p("<br>%s", strings.Join(f.decls, ", "))
			}
			p("\n")
		}
	}
	return w.Bytes(), nil
}

func goPackages(root string) ([]*pkg, error) {
	byDir := map[string]*pkg{}
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			// docsgen is its own module; vendor and dot dirs are not ours.
			if rel != "." && (strings.HasPrefix(d.Name(), ".") || rel == "tools/docsgen" || rel == "web" || d.Name() == "testdata" || d.Name() == "node_modules") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		af, err := parser.ParseFile(fset, path, src, parser.ParseComments)
		if err != nil {
			return err
		}
		dir := filepath.ToSlash(filepath.Dir(rel))
		k := byDir[dir]
		if k == nil {
			k = &pkg{dir: dir, imports: map[string]bool{}}
			byDir[dir] = k
		}
		f := &file{name: filepath.Base(path)}
		isTest := strings.HasSuffix(path, "_test.go")
		if !isTest {
			if k.name == "" || af.Doc != nil {
				k.name = af.Name.Name
			}
			if af.Doc != nil && k.doc == "" {
				k.doc = firstSentence(af.Doc.Text())
			}
			for _, imp := range af.Imports {
				ip := strings.Trim(imp.Path.Value, `"`)
				if strings.HasPrefix(ip, module+"/") {
					k.imports[strings.TrimPrefix(ip, module+"/")] = true
				}
			}
		}
		f.purpose = filePurpose(af)
		for _, d := range af.Decls {
			for _, n := range declNames(d, fset, af.Name.Name == "main") {
				if isTest {
					if strings.HasPrefix(n.name, "Test") || strings.HasPrefix(n.name, "Benchmark") || strings.HasPrefix(n.name, "Fuzz") {
						f.tests = append(f.tests, n.name)
					}
					continue
				}
				f.decls = append(f.decls, n.name)
			}
		}
		if isTest {
			if len(f.tests) > 0 {
				k.tests = append(k.tests, f)
			}
		} else {
			k.files = append(k.files, f)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	var out []*pkg
	for _, k := range byDir {
		if len(k.files) == 0 {
			continue
		}
		sort.Slice(k.files, func(i, j int) bool { return k.files[i].name < k.files[j].name })
		sort.Slice(k.tests, func(i, j int) bool { return k.tests[i].name < k.tests[j].name })
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].dir < out[j].dir })
	return out, nil
}

type named struct {
	name string
	line int
}

// declNames lists a declaration's names: every function and method (the
// unexported ones are where most of the logic lives, such as peer.login),
// and exported types, constants and variables (every type in package main).
func declNames(d ast.Decl, fset *token.FileSet, all bool) []named {
	keep := func(n string) bool { return all || ast.IsExported(n) }
	var out []named
	switch d := d.(type) {
	case *ast.FuncDecl:
		name := d.Name.Name
		if d.Recv != nil && len(d.Recv.List) > 0 {
			name = recvName(d.Recv.List[0].Type) + "." + name
		}
		out = append(out, named{name, fset.Position(d.Pos()).Line})
	case *ast.GenDecl:
		if d.Tok != token.TYPE && d.Tok != token.CONST && d.Tok != token.VAR {
			return nil
		}
		for _, s := range d.Specs {
			switch s := s.(type) {
			case *ast.TypeSpec:
				if keep(s.Name.Name) {
					out = append(out, named{"type " + s.Name.Name, fset.Position(s.Pos()).Line})
				}
			case *ast.ValueSpec:
				// Exported constants and variables only: they are the
				// vocabulary (message types, defaults) worth finding.
				for _, n := range s.Names {
					if ast.IsExported(n.Name) {
						out = append(out, named{n.Name, fset.Position(n.Pos()).Line})
					}
				}
			}
		}
	}
	return out
}

func recvName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return recvName(t.X)
	case *ast.IndexExpr:
		return recvName(t.X)
	case *ast.IndexListExpr:
		return recvName(t.X)
	case *ast.Ident:
		return t.Name
	}
	return "?"
}

// filePurpose is the first sentence of the comment at the top of a file
// (before or as the package clause's doc), skipping build constraints.
func filePurpose(af *ast.File) string {
	if af.Doc != nil {
		return firstSentence(af.Doc.Text())
	}
	for _, cg := range af.Comments {
		if cg.Pos() > af.Package {
			break
		}
		t := cg.Text()
		if strings.HasPrefix(t, "go:build") || strings.HasPrefix(t, "+build") {
			continue
		}
		if s := firstSentence(t); s != "" {
			return s
		}
	}
	// Otherwise the doc of the first declaration says what the file is for.
	for _, d := range af.Decls {
		var doc *ast.CommentGroup
		switch d := d.(type) {
		case *ast.FuncDecl:
			doc = d.Doc
		case *ast.GenDecl:
			doc = d.Doc
		}
		if doc != nil {
			return firstSentence(doc.Text())
		}
	}
	return ""
}

var sentenceEnd = regexp.MustCompile(`\.(\s|$)`)

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(strings.SplitN(s, "\n\n", 2)[0]), " ")
	if loc := sentenceEnd.FindStringIndex(s); loc != nil {
		s = s[:loc[0]+1]
	}
	if len(s) > 220 {
		s = s[:217] + "..."
	}
	return s
}

var jsDecl = regexp.MustCompile(`^(?:export\s+)?(?:async\s+)?(?:function\*?\s+([A-Za-z0-9_$]+)|class\s+([A-Za-z0-9_$]+)|(?:const|let)\s+([A-Z][A-Z0-9_]+)\s*=)`)

func jsFile(path string) (*file, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	f := &file{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	line, head := 0, true
	var comment []string
	for sc.Scan() {
		line++
		t := sc.Text()
		if head {
			if c, ok := strings.CutPrefix(strings.TrimSpace(t), "//"); ok {
				comment = append(comment, strings.TrimSpace(c))
				continue
			}
			head = false
			f.purpose = firstSentence(strings.Join(comment, " "))
		}
		if m := jsDecl.FindStringSubmatch(t); m != nil {
			name := m[1] + m[2] + m[3]
			f.decls = append(f.decls, name)
		}
	}
	return f, sc.Err()
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func anchor(s string) string {
	return strings.Trim(regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(strings.ToLower(s), "-"), "-")
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
